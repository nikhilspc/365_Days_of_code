class Variable {
    public static void main(String[] args) {
        
        // Declaring and initializing variables
        
        // Integer variable  
        int age = 25;       
        String name = "ram"; 
        
        // Double variable 
        double salary = 50000.50;     

        System.out.println("Age: " + age);          
        System.out.println("Name: " + name);        
        System.out.println("Salary: " + salary);
    }
}